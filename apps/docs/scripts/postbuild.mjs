#!/usr/bin/env node
/*
 * Runs after `astro build`. Two jobs:
 *
 * 1. A second, independent link check over the built HTML: every internal href and src must
 *    resolve to a file in dist/ (starlight-links-validator already checked the Markdown links
 *    and anchors during the build; this also covers components, assets and the generated
 *    reference pages). Any broken link fails the build.
 *
 * 2. dist/_headers for Cloudflare Workers static assets:
 *    - Content-Security-Policy. Scripts: 'self' plus the SHA-256 of each inline script Starlight
 *      emits (theme, sidebar, search shortcut), computed here from the built HTML, and
 *      'wasm-unsafe-eval' for the Pagefind search index. Styles: 'self' and 'unsafe-inline',
 *      because Starlight and Expressive Code set CSS custom properties in style attributes (one
 *      distinct value per token colour: too many to hash). The site has no user input and loads
 *      nothing from another origin. Nothing may frame it.
 *    - Pre-rendered diagram SVGs are served with their own policy that allows their internal
 *      <style> (an <img> SVG can never run script).
 *    - X-Robots-Tag: noindex (staging), HSTS, caching for fingerprinted assets.
 */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const DIST = fileURLToPath(new URL("../dist/", import.meta.url));

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : [path];
  });
}

const html = files(DIST).filter((f) => f.endsWith(".html"));
const sha256 = (text) => `'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`;

// --- 1. Link check ------------------------------------------------------------------------
const broken = [];
function resolves(path) {
  const clean = decodeURI(path.split("#")[0].split("?")[0]);
  if (clean === "" || clean === "/") return existsSync(join(DIST, "index.html"));
  const target = join(DIST, clean);
  if (clean.endsWith("/")) return existsSync(join(target, "index.html"));
  return (
    existsSync(target) || existsSync(join(target, "index.html")) || existsSync(`${target}.html`)
  );
}
for (const file of html) {
  const text = readFileSync(file, "utf8");
  const rel = relative(DIST, file);
  for (const m of text.matchAll(/\s(?:href|src)="([^"]+)"/g)) {
    const url = m[1];
    if (/^(https?:|mailto:|data:|#|\/\/)/.test(url)) continue;
    const absolute = url.startsWith("/") ? url : `/${join(relative(DIST, join(file, "..")), url)}`;
    if (!resolves(absolute)) broken.push(`${rel}: ${url}`);
  }
}
if (broken.length > 0) {
  console.error(`postbuild: ${broken.length} broken internal link(s):`);
  for (const b of [...new Set(broken)]) console.error(`  - ${b}`);
  process.exit(1);
}

// --- 2. Headers ---------------------------------------------------------------------------
const scriptHashes = new Set();
for (const file of html) {
  const text = readFileSync(file, "utf8");
  for (const m of text.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attrs = m[1] ?? "";
    if (/\bsrc\s*=/.test(attrs)) continue;
    if (/type\s*=\s*["']?application\/(ld\+)?json/i.test(attrs)) continue;
    scriptHashes.add(sha256(m[2] ?? ""));
  }
  if (/<style\b/i.test(text)) {
    console.error(
      `postbuild: ${relative(DIST, file)} has an inline <style> block; move it to CSS.`,
    );
    process.exit(1);
  }
}

const csp = [
  "default-src 'none'",
  `script-src 'self' 'wasm-unsafe-eval' ${[...scriptHashes].sort().join(" ")}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "manifest-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
  "object-src 'none'",
].join("; ");

const headers = `# Generated by scripts/postbuild.mjs. Do not edit.
/*
  Content-Security-Policy: ${csp}
  X-Robots-Tag: noindex, nofollow
  Referrer-Policy: strict-origin-when-cross-origin
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Cross-Origin-Opener-Policy: same-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), publickey-credentials-get=(), publickey-credentials-create=(), browsing-topics=()
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Cache-Control: no-cache, must-revalidate

/diagrams/*
  ! Content-Security-Policy
  ! Cache-Control
  Content-Security-Policy: default-src 'none'; style-src 'unsafe-inline'; img-src data:
  Cache-Control: public, max-age=3600

/_assets/*
  ! Cache-Control
  Cache-Control: public, max-age=31536000, immutable

/fonts/*
  ! Cache-Control
  Cache-Control: public, max-age=604800

/pagefind/*
  ! Cache-Control
  Cache-Control: public, max-age=3600
`;

for (const line of headers.split("\n")) {
  if (line.length > 2000) {
    console.error("postbuild: a header line exceeds 2000 characters");
    process.exit(1);
  }
}
writeFileSync(join(DIST, "_headers"), headers);
console.log(
  `postbuild: ${html.length} pages, internal links ok; _headers written (${scriptHashes.size} inline script hashes)`,
);
