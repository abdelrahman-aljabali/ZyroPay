#!/usr/bin/env node
/*
 * Runs after `astro build`. Writes dist/_headers for Cloudflare Workers static assets:
 *
 *   - a strict Content-Security-Policy: no 'unsafe-inline' and no 'unsafe-eval'. The few inline
 *     scripts Astro emits for island hydration are allowed by their SHA-256 hashes, computed here
 *     from the built HTML. Only the real app (for "Open the app") and, once configured, the demo
 *     video's player may be framed, and this page cannot be framed (frame-ancestors 'none');
 *   - a Permissions-Policy that delegates passkeys and clipboard writes to that one origin, so
 *     WebAuthn can work inside the framed app; everything else stays off;
 *   - X-Robots-Tag: noindex on every response (the pages also carry <meta name="robots">);
 *   - long-lived caching for fingerprinted assets.
 *
 * Inline <style> blocks (Astro's island rule) are hashed the same way. The build fails if any
 * page contains an inline style attribute, because the CSP does not allow them.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const DIST = fileURLToPath(new URL("../dist/", import.meta.url));
/** The real app, framed by "Open the app" on desktop. */
const APP_ORIGIN = "https://app.zyropay.online";

/*
 * The demo video (config/showcase.json, shared with the docs site): its player origin may be
 * framed, a direct video file may play and a remote poster may load. Only https origins, and
 * only once the config names them. src/lib/showcase.ts applies the same rules to the markup.
 */
const SHOWCASE = JSON.parse(
  readFileSync(fileURLToPath(new URL("../../../config/showcase.json", import.meta.url)), "utf8"),
);
const origin = (u) => {
  try {
    const url = new URL(String(u));
    return url.protocol === "https:" ? url.origin : null;
  } catch {
    return null;
  }
};
const VIDEO_FRAME = origin(SHOWCASE.video?.embedUrl);
const VIDEO_FILE = /\.(mp4|webm|m4v|mov)(\?|#|$)/i.test(String(SHOWCASE.video?.url ?? ""))
  ? origin(SHOWCASE.video?.url)
  : null;
const POSTER = origin(SHOWCASE.video?.poster);

function htmlFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return htmlFiles(path);
    return name.endsWith(".html") ? [path] : [];
  });
}

const sha256 = (text) => `'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`;

const scriptHashes = new Set();
const styleHashes = new Set();
const problems = [];

for (const file of htmlFiles(DIST)) {
  const html = readFileSync(file, "utf8");
  const rel = relative(DIST, file);

  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attrs = m[1] ?? "";
    const body = m[2] ?? "";
    if (/\bsrc\s*=/.test(attrs)) continue;
    if (/type\s*=\s*["']?application\/(ld\+)?json/i.test(attrs)) continue;
    scriptHashes.add(sha256(body));
  }
  // Astro's own `astro-island { display: contents }` rule: allowed by hash, like the scripts.
  for (const m of html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)) {
    styleHashes.add(sha256(m[1] ?? ""));
  }
  for (const m of html.matchAll(/\sstyle\s*=\s*["'][^"']*["']/gi)) {
    problems.push(`${rel}: inline style attribute ${m[0].trim().slice(0, 60)}`);
  }
}

if (problems.length > 0) {
  console.error(
    "postbuild: the CSP forbids inline style attributes. Move these into a stylesheet:",
  );
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

const csp = [
  "default-src 'none'",
  `script-src 'self' ${[...scriptHashes].sort().join(" ")}`.trim(),
  `style-src 'self' ${[...styleHashes].sort().join(" ")}`.trim(),
  ["img-src 'self' data:", POSTER].filter(Boolean).join(" "),
  "font-src 'self'",
  "connect-src 'self'",
  ["frame-src", APP_ORIGIN, VIDEO_FRAME].filter(Boolean).join(" "),
  ["media-src 'self'", VIDEO_FILE].filter(Boolean).join(" "),
  "manifest-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
  "object-src 'none'",
].join("; ");

const headers = `# Generated by scripts/postbuild.mjs. Do not edit.
/*
  Content-Security-Policy: ${csp}
  X-Robots-Tag: noindex, nofollow
  Referrer-Policy: strict-origin-when-cross-origin
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Cross-Origin-Opener-Policy: same-origin
  Permissions-Policy: publickey-credentials-get=(self "${APP_ORIGIN}"), publickey-credentials-create=(self "${APP_ORIGIN}"), clipboard-write=(self "${APP_ORIGIN}"), camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()
  Strict-Transport-Security: max-age=31536000; includeSubDomains

# HTML always revalidates, so a fix is visible on the next load.
/
  Cache-Control: no-cache, must-revalidate

/legal
  Cache-Control: no-cache, must-revalidate

/*.html
  Cache-Control: no-cache, must-revalidate

/_assets/*
  Cache-Control: public, max-age=31536000, immutable

/fonts/*
  Cache-Control: public, max-age=604800

/brand/*
  Cache-Control: public, max-age=604800

/icons/*
  Cache-Control: public, max-age=604800
`;

writeFileSync(join(DIST, "_headers"), headers);
console.log(
  `postbuild: _headers written (${scriptHashes.size} inline script hash${scriptHashes.size === 1 ? "" : "es"})`,
);
